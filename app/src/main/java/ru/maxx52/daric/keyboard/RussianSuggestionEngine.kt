    private val sentenceStarters = listOf(
        "привет", "доброе", "спасибо", "сегодня", "давай", "можно", "я"
    )

    override fun suggest(context: SuggestionContext, limit: Int): List<String> {
        if (limit <= 0) return emptyList()

        val prefix = context.currentWord.lowercase(russianLocale)
        val contextual = contextModel.predictNext(
            previousWords = context.previousWords,
            limit = limit * CONTEXT_CANDIDATE_MULTIPLIER
        )

        val candidates = if (prefix.isBlank()) {
            contextual.ifEmpty { sentenceStarters }
        } else {
            buildList {
                addAll(contextual.filter { candidate -> candidate.startsWith(prefix) })
                addAll(words.filter { word -> word.startsWith(prefix) })
            }
        }

        return candidates.asSequence()
            .map { it.lowercase(russianLocale) }
            .filter { candidate -> candidate.isNotBlank() && candidate != prefix }
            .distinct()
            .take(limit)
            .toList()
    }

    private const val CONTEXT_CANDIDATE_MULTIPLIER = 4
}

private object RussianPhraseLanguageModel : ContextLanguageModel {

    private val transitions = mapOf(
        "доброе" to listOf("утро"),
        "добрый" to listOf("день", "вечер"),
        "спокойной" to listOf("ночи"),
        "хорошего" to listOf("дня", "вечера", "настроения"),
        "с" to listOf("праздником", "любовью"),
        "с днём" to listOf("рождения"),
        "с днем" to listOf("рождения"),
        "днём" to listOf("рождения"),
        "днем" to listOf("рождения"),
        "спасибо" to listOf("большое", "за"),
        "спасибо за" to listOf("помощь", "поддержку", "поздравление"),
        "как" to listOf("дела", "ты", "вы"),
        "до" to listOf("встречи", "завтра"),
        "до встречи" to listOf("завтра"),
        "я" to listOf("думаю", "хочу", "буду", "могу"),
        "я буду" to listOf("дома", "работать", "ждать"),
        "всё" to listOf("хорошо", "работает", "готово"),
        "все" to listOf("хорошо", "работает", "готово"),
        "не" to listOf("знаю", "могу", "нужно"),
        "можно" to listOf("сделать", "добавить", "проверить"),
        "нужно" to listOf("сделать", "проверить", "добавить"),
        "давай" to listOf("сделаем", "проверим", "продолжим"),
        "давайте" to listOf("сделаем", "проверим", "продолжим"),
        "сегодня" to listOf("буду", "можно", "вечером"),
        "бог" to listOf("благословит"),
        "господь" to listOf("благословит"),
        "слава" to listOf("богу"),
        "христос" to listOf("воскрес")
    )

    override fun predictNext(previousWords: List<String>, limit: Int): List<String> {
        if (previousWords.isEmpty() || limit <= 0) return emptyList()

        val normalizedWords = previousWords.map { it.lowercase() }
        return buildList {
            for (wordCount in minOf(MAX_CONTEXT_WORDS, normalizedWords.size) downTo 1) {
                val key = normalizedWords.takeLast(wordCount).joinToString(" ")
                transitions[key]?.let(::addAll)
            }
        }.distinct().take(limit)
    }

    private const val MAX_CONTEXT_WORDS = 3
}
